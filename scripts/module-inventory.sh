#!/usr/bin/env bash
# Module inventory (SUPERB v17 T11): the machine-checkable module → newest-tag
# index, generated from ORIGIN state so it cannot drift at tag time.
#
#   ./scripts/module-inventory.sh           # regenerate docs/MODULE_INVENTORY.md
#   ./scripts/module-inventory.sh --check   # fail if the committed table is stale
#
# The table reports the newest tag ON ORIGIN per module (what a fresh consumer
# actually resolves) plus local-only tags as an informational column. Because
# a brand-new local tag is invisible to origin, `--check` stays green through
# the whole release window (tag → pre-tag-checks → push) and the post-push
# re-run (the deferred-leg slot, alongside check-gosum-canonical) is what
# lands the updated row on master. Offline: degrades to local-only with a
# loud NOTE and passes --check (same posture as check-pin-drift.sh).
#
# The module map MUST stay in lockstep with tag_pattern() in
# scripts/check-pin-drift.sh — extend both together.

set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

out="docs/MODULE_INVENTORY.md"
mode="${1:-regen}"

# --- origin tag state (one roundtrip, cached) --------------------------------
origin_tags="$(git ls-remote --tags origin 2>/dev/null | sed -n 's|.*refs/tags/\([^^]*\)$|\1|p' || true)"
origin_reachable=1
if [[ -z "$origin_tags" ]]; then
	echo "NOTE: origin unreachable (ls-remote failed) — inventory degraded to LOCAL-only truth (--check passes with the note)"
	origin_reachable=0
fi

# module_dir <short>: the go.work directory for a short name.
module_dir() {
	case "$1" in
	core) echo "." ;;
	frh) echo "flightrecorderhealth" ;;
	*) echo "$1" ;;
	esac
}

# tag_pattern <short>: identical to tag_pattern() in check-pin-drift.sh.
tag_pattern() {
	case "$1" in
	core) echo "v*" ;;
	cqrs | otel | flightrecorder | health | realtime | docs | errorpages | security | systemd | config | preset | httpx) echo "$1/v*" ;;
	frh) echo "flightrecorderhealth/v*" ;;
	*) return 1 ;;
	esac
}

shorts=(core cqrs realtime security otel flightrecorder frh health httpx docs errorpages systemd config preset)

rows=""
for short in "${shorts[@]}"; do
	pattern="$(tag_pattern "$short")"
	dir="$(module_dir "$short")"

	local_latest="$(git tag -l -- "$pattern" | sort -V | tail -n1)"

	origin_latest=""
	if [[ "$origin_reachable" == 1 ]]; then
		origin_latest="$(printf '%s\n' "$origin_tags" | grep -- "$pattern" | sed 's|^\([^^]*\)$|\1|' | sort -V | tail -n1 || true)"
	fi

	latest="${origin_latest:-$local_latest}"
	local_only="—"
	if [[ -n "$local_latest" && "$local_latest" != "$origin_latest" ]]; then
		local_only="$local_latest"
	fi

	if [[ "$short" == "core" ]]; then
		import="github.com/larsartmann/go-appkit"
	else
		import="github.com/larsartmann/go-appkit/$dir"
	fi

	if [[ -z "$latest" ]]; then
		latest="(none)"
		local_only="—"
	fi

	rows+="| \`$short\` | \`$import\` | \`$latest\` | \`$local_only\` |"$'\n'
done

content="# Module inventory — newest tags per module

> GENERATED by \`scripts/module-inventory.sh\` — do not edit by hand; re-run it.
> Origin-truth index (what a fresh \`go get\` resolves right now); the
> \`local-only\` column carries tags that exist locally but not yet on origin
> (the release window). Capability truth lives in [CAPABILITIES.md](CAPABILITIES.md).

**As of:** $(date -u +%Y-%m-%d_%H:%M) UTC$( [[ "$origin_reachable" == 0 ]] && echo ' · DEGRADED: origin unreachable, local truth shown' || true)

| Module | Import path | Newest on origin | Local-only |
| ------ | ----------- | ---------------- | ---------- |
$rows
"

if [[ "$mode" == "--check" ]]; then
	if [[ ! -f "$out" ]]; then
		echo "FAIL: $out missing — run ./scripts/module-inventory.sh and commit the result"
		exit 1
	fi

	# Normalize before diffing: the committed file is dprint-aligned (table
	# padding) and carries a generation timestamp — neither is inventory
	# truth. Compare ROW CONTENT only (pipes collapsed, As-of line dropped).
	normalize() {
		grep -v '^\*\*As of:\*\*' \
			| sed 's/[[:space:]]*|[[:space:]]*/|/g; s/^[[:space:]]*//; s/[[:space:]]*$//'
	}

	if diff -u <(normalize <"$out") <(printf '%s' "$content" | normalize) >/tmp/module-inventory.diff 2>&1; then
		echo "OK:   module inventory current ($(grep -c '^| `' "$out") module rows)"
		rm -f /tmp/module-inventory.diff
	else
		echo "FAIL: module inventory is STALE vs origin — fix:"
		echo "  ./scripts/module-inventory.sh && git add $out   # then commit before pushing master"
		cat /tmp/module-inventory.diff
		exit 1
	fi
else
	printf '%s' "$content" >"$out"
	echo "OK:   wrote $out ($(wc -l <<<"$rows") modules; origin $([[ "$origin_reachable" == 1 ]] && echo reachable || echo UNREACHABLE))"
fi
